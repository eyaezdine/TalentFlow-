import React from 'react';
import { describe, it, expect, vi, beforeEach } from 'vitest';
import { render, screen, waitFor, fireEvent } from '@testing-library/react';
import Jobs from '../pages/Jobs';
import api from '../api/client';

vi.mock('../api/client', () => ({
  default: {
    get: vi.fn(),
    post: vi.fn(),
    put: vi.fn(),
    delete: vi.fn(),
  },
}));

vi.mock('../context/AuthContext', () => ({
  useAuth: () => ({ user: { id: 'user-1', name: 'Aziz', role: 'RECRUITER' } }),
}));

const PROMPT = "Offre d'emploi pour un ingénieur Spring Boot avec 2 ans d'expérience, Java, API REST et MySQL";

const aiOffer = {
  title: 'Ingénieur Backend Java / Spring Boot',
  description: 'Développement et maintenance d’applications backend.',
  responsibilities: ['Développer des API REST', 'Participer à la conception des services backend'],
  requiredSkills: ['Java', 'Spring Boot', 'API REST', 'MySQL'],
  preferredSkills: ['Docker'],
  experience: '2 ans',
  education: null,
  employmentType: 'Full-time',
  location: 'Remote',
  salary: null,
  profile: 'Profil technique autonome et rigoureux.',
  benefits: ['Mutuelle'],
};

const openCreateModal = async () => {
  render(<Jobs />);
  fireEvent.click(screen.getByRole('button', { name: /New Job Opening/i }));
  await waitFor(() => {
    expect(screen.getByPlaceholderText(/Senior Java Developer/i)).toBeInTheDocument();
  });
  return screen.getByPlaceholderText(/Senior Java Developer/i);
};

describe('Jobs page - AI job offer generation', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    api.get.mockResolvedValue({ data: { data: [], pagination: null } });
  });

  it('calls the right endpoint and fills the form without saving automatically', async () => {
    api.post.mockResolvedValueOnce({ data: aiOffer });

    const promptInput = await openCreateModal();
    fireEvent.change(promptInput, { target: { value: PROMPT } });
    fireEvent.click(screen.getByRole('button', { name: /Generate/i }));

    await waitFor(() => {
      expect(screen.getByDisplayValue(aiOffer.title)).toBeInTheDocument();
    });

    expect(api.post).toHaveBeenCalledWith('/ai/job-offer/generate', { prompt: PROMPT });

    // Skills generated by the AI are mapped into the existing form field
    expect(screen.getByDisplayValue('Java, Spring Boot, API REST, MySQL')).toBeInTheDocument();

    // Responsibilities / profile / experience are merged into the description textarea
    const description = screen.getByDisplayValue(/Key Responsibilities/i);
    expect(description.value).toContain('Développer des API REST');
    expect(description.value).toContain('Experience: 2 ans');

    // The offer is NOT persisted until the recruiter submits the form
    expect(api.post).not.toHaveBeenCalledWith('/jobs', expect.anything());
  });

  it('allows manual editing of the generated fields', async () => {
    api.post.mockResolvedValueOnce({ data: aiOffer });

    const promptInput = await openCreateModal();
    fireEvent.change(promptInput, { target: { value: PROMPT } });
    fireEvent.click(screen.getByRole('button', { name: /Generate/i }));

    await waitFor(() => {
      expect(screen.getByDisplayValue(aiOffer.title)).toBeInTheDocument();
    });

    const titleInput = screen.getByDisplayValue(aiOffer.title);
    fireEvent.change(titleInput, { target: { value: 'Ingénieur Backend Senior' } });

    expect(screen.getByDisplayValue('Ingénieur Backend Senior')).toBeInTheDocument();
    expect(api.post).not.toHaveBeenCalledWith('/jobs', expect.anything());
  });

  it('shows the backend error message and keeps the user input', async () => {
    api.post.mockRejectedValueOnce({
      code: 'AI_CONFIG_ERROR',
      message: 'No AI API key is configured.',
      status: 503,
    });

    const promptInput = await openCreateModal();
    fireEvent.change(promptInput, { target: { value: PROMPT } });
    fireEvent.click(screen.getByRole('button', { name: /Generate/i }));

    await waitFor(() => {
      expect(screen.getByText('No AI API key is configured.')).toBeInTheDocument();
    });

    // The recruiter's description is preserved so it can be retried
    expect(screen.getByDisplayValue(PROMPT)).toBeInTheDocument();
  });

  it('validates the prompt client-side before calling the API', async () => {
    await openCreateModal();
    fireEvent.click(screen.getByRole('button', { name: /Generate/i }));

    await waitFor(() => {
      expect(screen.getByText(/at least 10 characters/i)).toBeInTheDocument();
    });

    expect(api.post).not.toHaveBeenCalled();
  });
});
